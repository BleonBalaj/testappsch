export const translations = Object.freeze({ en: Object.freeze(en), sq: Object.freeze(sq) });

export function translate(language, key, values = {}) {
  const locale = String(language ?? 'en').toLowerCase().startsWith('sq') ? 'sq' : 'en';
  const template = translations[locale][key] ?? translations.en[key] ?? key;
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
}

