"use client";
import { memo, useCallback, useEffect, useLayoutEffect, useRef, useState } from "react";
import { observeDialogOverlays } from "../../features/theme/dialog-overlays";
import { observeNatureGlassEntries } from "../../features/theme/nature-glass-entry";
import { observeNaturePausedCardPaint } from "../../features/theme/nature-paused-card-paint";
import { useThemeMode } from "../../features/theme/useThemeMode";
const toast = ({ title, description }) => window.dispatchEvent(new CustomEvent("nature:notice", { detail: { title, description } }));
import { NATURE_PHASES, NATURE_PHASE_EVENT, NATURE_PHASE_KEY, NATURE_MOTION_KEY, NATURE_MOTION_EVENT, NATURE_SEASON_KEY, NATURE_SEASON_EVENT, readNatureSeason, resolveNatureSeason, createNaturePhaseTransition, readNaturePhasePref, readNatureMotionPaused, pauseNatureForPerformance, resolveNaturePhase, } from "../../features/theme/nature-phase";
/**
 * Nature theme only. Renders nothing (and attaches no listeners) unless
 * <html> carries `theme-nature`, so every other theme is untouched.
 *
 * - Keeps `data-nature-phase` (morning | golden | night) on <html> in sync with
 *   the user's sub-setting (Auto follows local time); nature-theme.css keys off it.
 * - Hosts the WebGL meadow in a same-origin iframe (public/nature/scene.html,
 *   generated by scripts/build-nature-scene.cjs) so its renderer, globals and
 *   styles stay isolated from the app.
 */
export const NatureBackground = memo(function NatureBackground({ allowScene, publicPage = false }) {
    const isNature = useThemeMode() === "nature";
    if (!isNature)
        return null;
    return <NatureActive key={allowScene ? "scene" : "still"} allowScene={allowScene} publicPage={publicPage}/>;
});
function requestIdle(fn, timeout) {
    const w = window;
    if (typeof w.requestIdleCallback === "function") {
        const id = w.requestIdleCallback(fn, { timeout });
        return () => w.cancelIdleCallback(id);
    }
    const id = window.setTimeout(fn, Math.min(timeout, 600));
    return () => window.clearTimeout(id);
}
function NatureActive({ allowScene, publicPage }) {
    const [initialPhase] = useState(() => resolveNaturePhase(readNaturePhasePref()));
    const [initialMotionPaused] = useState(readNatureMotionPaused);
    const [initialSeason] = useState(() => resolveNatureSeason(readNatureSeason()));
    const [mountScene, setMountScene] = useState(false);
    const [loaded, setLoaded] = useState(false);
    const frameRef = useRef(null);
    const phaseRef = useRef(initialPhase);
    const seasonRef = useRef(initialSeason);
    const readyRef = useRef(false);
    const pausedRef = useRef(false);
    const motionPausedRef = useRef(initialMotionPaused);
    const manualResumeRef = useRef(false);
    const autoPausedRef = useRef(false);
    useLayoutEffect(() => {
        const main = document.querySelector("#root");
        if (!main)
            return;
        let paused = readNatureMotionPaused();
        const stopEntries = observeNatureGlassEntries(main, () => paused);
        let stopPaint;
        const sync = () => {
            paused = readNatureMotionPaused();
            if (paused && !stopPaint)
                stopPaint = observeNaturePausedCardPaint(main);
            else if (!paused && stopPaint) {
                stopPaint();
                stopPaint = undefined;
            }
        };
        const storage = (event) => { if (event.key === NATURE_MOTION_KEY || event.key === null)
            sync(); };
        sync();
        window.addEventListener(NATURE_MOTION_EVENT, sync);
        window.addEventListener("storage", storage);
        return () => { stopPaint?.(); stopEntries(); window.removeEventListener(NATURE_MOTION_EVENT, sync); window.removeEventListener("storage", storage); };
    }, []);
    const post = useCallback((msg) => {
        frameRef.current?.contentWindow?.postMessage(msg, window.location.origin);
    }, []);
    const onReady = useCallback(() => {
        if (readyRef.current)
            return;
        readyRef.current = true;
        post({ type: "nature:phase", index: phaseRef.current, instant: true });
        post({ type: "nature:season", season: seasonRef.current, instant: true });
        post({ type: "nature:pause", paused: pausedRef.current });
        post({ type: "nature:motion", paused: motionPausedRef.current });
        if (manualResumeRef.current)
            post({ type: "nature:motion", paused: motionPausedRef.current, autoDetect: false });
        setLoaded(true);
    }, [post]);
    // Phase: user's sub-setting, or the clock when on Auto.
    useEffect(() => {
        const root = document.documentElement;
        const transition = createNaturePhaseTransition(phaseRef.current);
        let transitionTimer = 0;
        let transitionEnd = 0;
        const sync = () => {
            if (!root.classList.contains("theme-nature"))
                return;
            const date = new Date();
            const next = resolveNaturePhase(readNaturePhasePref(), date);
            const now = performance.now();
            const phaseDuration = transition.change(next, now);
            const season = resolveNatureSeason(readNatureSeason(), date);
            const seasonChanged = season !== seasonRef.current;
            const duration = phaseDuration !== null || seasonChanged ? Math.max(phaseDuration ?? 0, seasonChanged ? 2600 : 0) : null;
            if (duration !== null) {
                root.style.setProperty("--nature-phase-duration", `${duration}ms`);
                root.dataset.natureTransitioning = "true";
                window.clearTimeout(transitionTimer);
                transitionEnd = Math.max(transitionEnd, now + duration);
                transitionTimer = window.setTimeout(() => {
                    delete root.dataset.natureTransitioning;
                }, transitionEnd - now);
            }
            root.dataset.naturePhase = NATURE_PHASES[next];
            root.dataset.natureSeason = season;
            // Morning/golden are light UIs, night is dark (components key off this).
            const style = next === 2 ? "dark" : "light";
            if (root.dataset.themeStyle !== style)
                root.dataset.themeStyle = style;
            phaseRef.current = next;
            if (phaseDuration !== null)
                post({ type: "nature:phase", index: next, duration: phaseDuration });
            if (seasonChanged) {
                seasonRef.current = season;
                post({ type: "nature:season", season });
            }
        };
        sync();
        const id = window.setInterval(sync, 30_000);
        const onVis = () => { if (document.visibilityState === "visible")
            sync(); };
        const onStorage = (e) => { if (e.key === NATURE_PHASE_KEY || e.key === NATURE_SEASON_KEY || e.key === null)
            sync(); };
        window.addEventListener(NATURE_PHASE_EVENT, sync);
        window.addEventListener(NATURE_SEASON_EVENT, sync);
        window.addEventListener("storage", onStorage);
        document.addEventListener("visibilitychange", onVis);
        return () => {
            window.clearInterval(id);
            window.removeEventListener(NATURE_PHASE_EVENT, sync);
            window.removeEventListener(NATURE_SEASON_EVENT, sync);
            window.removeEventListener("storage", onStorage);
            document.removeEventListener("visibilitychange", onVis);
            window.clearTimeout(transitionTimer);
            root.style.removeProperty("--nature-phase-duration");
            delete root.dataset.natureTransitioning;
            if (!root.classList.contains("theme-nature")) {
                delete root.dataset.naturePhase;
                delete root.dataset.natureSeason;
            }
        };
    }, [post]);
    // Build the scene only once the app has settled, so it never competes with
    // first paint / hydration. The painted sky gradient covers the gap.
    useEffect(() => {
        if (!allowScene) {
            return;
        }
        return requestIdle(() => setMountScene(true), 1500);
    }, [allowScene]);
    useEffect(() => {
        if (!mountScene)
            return;
        const onMessage = (e) => {
            if (e.origin !== window.location.origin || e.source !== frameRef.current?.contentWindow)
                return;
            if (e.data?.type === "nature:ready")
                onReady();
            if (e.data?.type === "nature:slow" && !autoPausedRef.current && !manualResumeRef.current &&
                !motionPausedRef.current && !pausedRef.current && document.visibilityState === "visible" &&
                document.documentElement.classList.contains("theme-nature")) {
                autoPausedRef.current = true;
                const publicVisit = document.documentElement.dataset.publicNaturePaused !== undefined;
                pauseNatureForPerformance();
                toast({ title: "Nature animations paused", duration: 12000,
                    description: publicVisit
                        ? "The animated background was running slowly on this device, so movement was paused for this public-page visit. Your app settings and the page’s saved defaults were not changed. Reopening this page starts with its saved setting."
                        : "The animated background was running slowly on this device, so we paused its movement to keep the app responsive. You can unpause it in Settings → Nature → Pause background movement." });
            }
        };
        window.addEventListener("message", onMessage);
        const syncMotion = (event) => {
            const scopeChanged = event?.detail?.scopeChanged === true;
            if (scopeChanged) {
                manualResumeRef.current = false;
                autoPausedRef.current = false;
            }
            const paused = readNatureMotionPaused();
            if (paused === motionPausedRef.current && !scopeChanged)
                return;
            motionPausedRef.current = paused;
            if (!paused && !scopeChanged)
                manualResumeRef.current = true;
            post({ type: "nature:motion", paused, ...(!paused ? { autoDetect: !manualResumeRef.current } : {}) });
        };
        const onMotionStorage = (event) => {
            if (event.key === NATURE_MOTION_KEY || event.key === null)
                syncMotion();
        };
        syncMotion();
        window.addEventListener(NATURE_MOTION_EVENT, syncMotion);
        window.addEventListener("storage", onMotionStorage);
        // Scrolling never suspends the meadow. A covering dialog suspends rendering;
        // the explicit motion preference freezes ambient movement separately.
        let dialogOpen = false;
        let lastPaused = null;
        const publishPause = () => {
            const paused = dialogOpen;
            pausedRef.current = paused;
            if (paused === lastPaused)
                return;
            lastPaused = paused;
            post({ type: "nature:pause", paused });
        };
        const stopDialogs = observeDialogOverlays(document.body, (open) => { dialogOpen = open; publishPause(); });
        // The iframe sits behind the app with pointer-events off, so forward the
        // pointer (rAF-throttled) for parallax. Grass responds only over exposed
        // meadow, never through cards, filter panels, headers or controls.
        let raf = 0;
        let x = 0;
        let y = 0;
        let grass = false;
        let pointerTarget = null;
        let lastX = -1, lastY = -1, lastGrass = false;
        const covered = '.glass, .sidebar, .main-header, .student-card, .staff-card, .class-card, .resource-card, [data-slot="card"], [data-slot="daily-briefing-card"], [class~="bg-card"], [class^="bg-card/"], [class*=" bg-card/"], .app-header, button, a, input, textarea, select, label, iframe, [role="dialog"], [role="menu"], [role="listbox"], [role="button"], .recharts-wrapper';
        const onPointer = (e) => {
            if (e.pointerType === "touch" || motionPausedRef.current)
                return;
            x = e.clientX;
            y = e.clientY;
            pointerTarget = e.target;
            if (raf)
                return;
            raf = requestAnimationFrame(() => {
                raf = 0;
                grass = !pointerTarget?.closest?.(covered);
                if (dialogOpen || motionPausedRef.current || (x === lastX && y === lastY && grass === lastGrass))
                    return;
                lastX = x;
                lastY = y;
                lastGrass = grass;
                post({ type: "nature:pointer", x, y, grass });
            });
        };
        window.addEventListener("pointermove", onPointer, { passive: true });
        return () => {
            window.removeEventListener("message", onMessage);
            window.removeEventListener("pointermove", onPointer);
            window.removeEventListener(NATURE_MOTION_EVENT, syncMotion);
            window.removeEventListener("storage", onMotionStorage);
            stopDialogs();
            if (raf)
                cancelAnimationFrame(raf);
        };
    }, [mountScene, onReady, post]);
    return (<>
      <div className="nature-top-fade" data-public-page={publicPage ? "true" : undefined} aria-hidden="true"/>
      <div className="nature-bottom-fade" aria-hidden="true"/>
      {allowScene && mountScene && (<iframe ref={frameRef} src={`/nature/scene.html?p=${initialPhase}&s=${initialSeason}&still=${initialMotionPaused ? 1 : 0}`} title="Nature background" aria-hidden="true" tabIndex={-1} 
        // Module scripts delay `load`, so the scene is built by now even if
        // its "nature:ready" message raced ahead of our listener.
        onLoad={onReady} className="nature-scene-frame" style={{ opacity: loaded ? 1 : 0, transition: "opacity 1.2s ease" }}/>)}
    </>);
}
