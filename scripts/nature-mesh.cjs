// Nature's private MarchingCubes copy. Preserve geometry math and capacity;
// avoid unused color work and upload only the vertices actually drawn.
function optimizeNatureMesh(source) {
  const replace = (from, to) => {
    if (source.split(from).length !== 2) throw new Error(`Nature mesh source changed: ${from}`);
    source = source.replace(from, to);
  };
  source = source.replace(/\r\n/g, '\n');
  // Cat-only opt-in: remember the rows touched by metaballs. Four neighbouring
  // rows cover all eight corners of each cube. Scan them in the original order
  // so vertices and normals remain byte-for-byte identical, including overlap.
  replace('this.normal_cache = new Float32Array( this.size3 * 3 );', `this.normal_cache = new Float32Array( this.size3 * 3 );
      this.natureRowMin = new Uint16Array( this.size2 );
      this.natureRowMin.fill( this.size );
      this.natureRowMax = new Uint16Array( this.size2 );`);
  replace('\t\t\t\t\ty_offset = z_offset + this.size * y;', `\t\t\t\t\ty_offset = z_offset + this.size * y;
          const row = z * this.size + y;
          this.natureRowMin[ row ] = Math.min( this.natureRowMin[ row ], min_x );
          this.natureRowMax[ row ] = Math.max( this.natureRowMax[ row ], max_x );`);
  for (const axis of ['X', 'Y', 'Z']) {
    replace(`this.addPlane${axis} = function ( strength, subtract ) {`, `this.addPlane${axis} = function ( strength, subtract ) {
      this.natureBoundedBalls = false; // planes are not represented by ball row bounds`);
  }
  replace('const smin2 = this.size - 2;', `const smin2 = this.size - 2;
      const bounded = this.natureBoundedBalls && this.isolation > 0;
      const lo = this.natureRowMin, hi = this.natureRowMax;`);
  replace('for ( let x = 1; x < smin2; x ++ ) {', `const row = z * this.size + y;
          const next = row + this.size;
          const minX = bounded ? Math.max( 1, Math.min( lo[row], lo[row + 1], lo[next], lo[next + 1] ) - 1 ) : 1;
          const maxX = bounded ? Math.min( smin2, Math.max( hi[row], hi[row + 1], hi[next], hi[next + 1] ) ) : smin2;
          for ( let x = minX; x < maxX; x ++ ) {`);
  replace('let ballColor = new Color( ballx, bally, ballz );', 'let ballColor = this.enableColors ? new Color( ballx, bally, ballz ) : null;');
  replace('if ( userDefineColor ) {', 'if ( this.enableColors && userDefineColor ) {');
  replace('\t\t\t\t\t\t\t// optimization', '\t\t\t\t\t\t\tif ( this.enableColors ) {\n\t\t\t\t\t\t\t// optimization');
  replace('this.palette[ ( y_offset + x ) * 3 + 2 ] += ballColor.b * contrib;', 'this.palette[ ( y_offset + x ) * 3 + 2 ] += ballColor.b * contrib;\n\t\t\t\t\t\t\t}');
  const begin = source.indexOf('\t\t\tfor ( let i = 0; i < this.size3; i ++ ) {');
  const end = source.indexOf('\n\t\t};', begin);
  if (begin < 0 || end < begin) throw new Error('Nature mesh reset changed');
  source = source.slice(0, begin) + '\t\t\tthis.normal_cache.fill( 0 );\n\t\t\tthis.field.fill( 0 );\n\t\t\tthis.natureRowMin.fill( this.size );\n\t\t\tthis.natureRowMax.fill( 0 );\n\t\t\tif ( this.enableColors ) this.palette.fill( 0 );\n' + source.slice(end);
  for (const name of ['position', 'normal']) {
    replace(`geometry.getAttribute( '${name}' ).needsUpdate = true;`, `const ${name} = geometry.getAttribute( '${name}' );
      ${name}.clearUpdateRanges();
      if ( this.count > 0 ) {
        ${name}.addUpdateRange( 0, Math.min( this.count * 3, ${name}.array.length ) );
        ${name}.needsUpdate = true;
      }`);
  }
  return '// Generated by scripts/build-nature-scene.cjs; Nature only.\n' + source;
}
module.exports = { optimizeNatureMesh };
